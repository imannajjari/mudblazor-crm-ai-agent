    public string this[string key] => Get(key);

    public string Get(string key)
    {
        if (Entries.TryGetValue(key, out var pair))
        {
            return Language == "fa" ? pair.Fa : pair.En;
        }
        return key;
    }

    public void SetLanguage(string lang)
    {
        Language = lang == "en" ? "en" : "fa";
    }

    public string LookupTerm(string term)
    {
        if (string.IsNullOrWhiteSpace(term)) return string.Empty;
        var q = term.Trim();
        if (Entries.TryGetValue(q, out var exactKey))
            return $"{exactKey.Fa} / {exactKey.En}";

        var matches = Entries.Values
            .Where(p => p.Fa.Equals(q, StringComparison.OrdinalIgnoreCase)
                     || p.En.Equals(q, StringComparison.OrdinalIgnoreCase)
                     || p.Fa.Contains(q, StringComparison.OrdinalIgnoreCase)
                     || p.En.Contains(q, StringComparison.OrdinalIgnoreCase))
            .Distinct()
            .Take(5)
            .Select(p => $"{p.Fa} = {p.En}")
            .ToArray();

        return matches.Length > 0 ? string.Join("; ", matches) : Get(q);
    }
